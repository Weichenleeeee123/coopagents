"""Safe, capability-reported MCP configuration for supported coding harnesses.

The adapters only edit explicit project configuration files. They never inspect
agent conversations or copy private credentials into a config file.
"""
from copy import deepcopy
from dataclasses import dataclass
import argparse
import json
from pathlib import Path
import os
import re
from urllib.parse import urlsplit


SUPPORTED_HARNESSES = ('cursor', 'opencode', 'pi', 'kimi-code', 'zcode', 'windsurf')

# OpenCode 2.x (current 2.2.7, checked 2026-11-12) groups MCP servers under
# mcp.servers and replaces the V1 `enabled` field with the inverse `disabled`;
# the V1 shape is normalized by V2, so it stays available as variant v1.
OPENCODE_VARIANTS = ('v1', 'v2')
OPENCODE_DEFAULT_VARIANT = 'v2'


class ConfigConflict(ValueError):
    """An existing MCP entry differs from the Coopagents entry being installed."""


@dataclass(frozen=True)
class HarnessSpec:
    harness: str
    config_path: str
    format: str
    config_scope: str = 'project'
    native_hook: str = 'unknown'
    idle_wake: str = 'unsupported'
    notes: str = ''


