'use strict';
const assert = require('node:assert/strict');
const model = require('../docs/prototypes/project-workspace/data.js');
const route = model.parseRoute('#/atlas/context?tab=files&item=file%3Af1&mode=read');
assert.deepEqual(route, {project:'atlas', view:'context', tab:'files', item:'file:f1', mode:'read'});
assert.equal(model.parseRoute('#/unknown/elsewhere').project, 'atlas');
assert.equal(model.parseRoute('#/atlas/context?tab=elsewhere').tab, 'agreements');
assert.equal(model.parseRoute('#/atlas/tasks?item=delivery%3Ad1').item, '');
assert.equal(model.parseRoute('#/relay/tasks?item=task%3At1').item, '');
assert.equal(model.parseRoute('#/atlas/tasks?item=task%3At1').item, 'task:t1');
assert.deepEqual(model.parseRoute(model.routeURL(route)), route);
const atlas=model.projects.find(p=>p.id==='atlas');
assert.equal(model.filterTasks(atlas, '上下文', 'all', '').length, 1);
assert.equal(model.filterTasks(atlas, '', 'working', '').length, 3);
assert.equal(model.filterTasks(atlas, '', 'active', '').length, 7);
assert.equal(model.filterTasks(atlas, '', 'all', '').length, 8);
assert.equal(model.filterTasks(atlas, '', 'all', 'm2').length, 3);
const related=model.relations(atlas, 't1');
assert.ok(related.deliveries.some(d=>d.id==='d1'));
assert.ok(related.requests.some(r=>r.id==='r1'));
assert.ok(atlas.deliveries.find(d=>d.id==='d1').taskIds.includes('t1'));
assert.equal(model.projects.find(p=>p.id==='blank').tasks.length,0);
assert.equal(model.parseRoute('#/atlas/settings?tab=diagnostics&mode=read').mode,'read');
assert.equal(model.parseRoute('#/atlas/members?tab=matrix&item=agent%3Aa1').tab,'people');
assert.equal(model.parseRoute('#/atlas/tasks').tab,'board');
assert.equal(model.parseRoute('#/atlas/tasks').tab,'board');
assert.equal(model.parseRoute('#/atlas/context?tab=records&item=contract%3Ac1').item,'');
assert.equal(model.parseRoute('#/atlas/context?tab=agreements&item=contract%3Ac1').item,'contract:c1');
assert.equal(model.parseRoute('#/blank/delivery?tab=all&item=delivery%3Ad1').item,'');
assert.equal(model.teams.find(t=>t.id==='team1').projects.length,2);
assert.ok(model.graphEdges(atlas).length>=9);
assert.equal(model.graphEdges(atlas).filter(edge=>edge.to==='g10').length,2);
assert.ok(model.graphEdges(atlas).length>=9);
assert.equal(model.graphEdges(atlas).filter(edge=>edge.to==='g10').length,2);
assert.notEqual(model.currentUser.id,model.projects[1].members[0].id);
console.log('Workspace prototype: scoped routes, restored tabs, task filters, object relationships and empty project passed');
